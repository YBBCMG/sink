  /* 出口判定用**精确格**：带 ±1 容差会让"站在出口旁边"也被判定成踩上去了
     （archive 的出生点 (10,12) 就紧邻它自己的出口 (10,13)，容差版会一进门就被弹回镇子） */
  function portalAt(sid, x, y) {
    var sc = SCENES[sid]; if (!sc) return null;
    for (var i = 0; i < sc.portals.length; i++) {
      var p = sc.portals[i];
      if (p.x === x && p.y === y) return p;
    }
    return null;
  }
  function isSolidIn(sid, x, y) {
    var sc = SCENES[sid]; if (!sc) return true;
    if (x < 0 || y < 0 || x >= sc.w || y >= sc.h) return true;
    for (var i = 0; i < sc.solids.length; i++) {
      var s = sc.solids[i];
      if (x >= s[0] && y >= s[1] && x < s[0] + s[2] && y < s[1] + s[3]) return true;
    }
    for (var j = 0; j < sc.places.length; j++) {
      var p = sc.places[j];
      if (p.kind !== 'portal' && p.kind !== 'look' && p.kind !== 'jobs' && p.x === x && p.y === y) return true;
    }
    return false;
  }
