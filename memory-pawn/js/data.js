  /* ---------- 失忆渲染（招牌机制） ---------- */

  function blackout(text) {
    return String(text).replace(/[^\s]/g, '■');
  }

  function memById(id) {
    for (var i = 0; i < MEMORIES.length; i++) if (MEMORIES[i].id === id) return MEMORIES[i];
    return null;
  }

  function memStateOf(S, id) {
    if (S && S.mem && S.mem[id]) return S.mem[id].state;
    return 'held';
  }

  /* 模板：{{mem:id}} → 原文 / ■■■（可赎）/ ▨▨▨（断当）；{{kw:tag}} → tag / ？？？ */
  function resolveText(raw, S) {
    var out = String(raw);
    out = out.replace(/\{\{mem:([a-z0-9_]+)\}\}/g, function (_, id) {
      var m = memById(id);
      if (!m) return '';
      var st = memStateOf(S, id);
      if (st === 'held') return '<span class="mem-hold">' + m.text + '</span>';
      var blk = blackout(m.text);
      return st === 'lost'
        ? '<span class="mem-lost">' + blk + '</span>'
        : '<span class="mem-blk">' + blk + '</span>';
    });
    out = out.replace(/\{\{kw:([^}]+)\}\}/g, function (_, tag) {
      var alive = 0;
      for (var i = 0; i < MEMORIES.length; i++) {
        if (MEMORIES[i].tag === tag && memStateOf(S, MEMORIES[i].id) === 'held') alive++;
      }
      return alive > 0 ? tag : '<span class="kw-blk">？？？</span>';
    });
    return out;
  }

  /* ---------- 数值纯函数 ---------- */

  function integrityOf(S) {
    var w = 0;
    for (var i = 0; i < MEMORIES.length; i++) {
      if (memStateOf(S, MEMORIES[i].id) === 'held') w += MEMORIES[i].w;
    }
    return w / TOTAL_W;
  }

  function lostCountOf(S) {
    var n = 0;
    for (var i = 0; i < MEMORIES.length; i++) {
      if (memStateOf(S, MEMORIES[i].id) === 'lost') n++;
    }
    return n;
  }

  function pawnedOf(S) {
    var arr = [];
    for (var i = 0; i < MEMORIES.length; i++) {
      if (memStateOf(S, MEMORIES[i].id) === 'pawned') arr.push(MEMORIES[i]);
    }
    return arr;
  }

  function earliestRedeemOf(S) {
    var best = -1;
    for (var i = 0; i < MEMORIES.length; i++) {
      var st = S.mem && S.mem[MEMORIES[i].id];
      if (st && st.state === 'pawned') {
        var left = CFG.REDEEM_SECONDS - (S.t - st.pawnedAt);
        if (best < 0 || left < best) best = left;
      }
    }
    return best;
  }

  function canBuy(S, ticketId) {
    for (var i = 0; i < SHOP.length; i++) {
      var g = SHOP[i];
      if (g.id !== ticketId) continue;
      if ((S.gold || 0) < g.cost) return { ok: false, why: '当金不够（还差 ' + (g.cost - (S.gold || 0)) + ' 枚）' };
      if (g.needMem) {
        var st = memStateOf(S, g.needMem);
        if (st !== 'pawned' && st !== 'lost') return { ok: false, why: '老板摇头："我手上没有那段记忆，抽不出这把钥匙。你还没把它卖给我。"' };
      }
      if (S.items && S.items[ticketId]) return { ok: false, why: '这个你已经有了。' };
      return { ok: true, why: '', goods: g };
    }
    return { ok: false, why: '没有这件东西。' };
  }

  /* 雾门终局资格：blank 红线优先；有断当 → half（她拼不出你）；否则可进最终抉择 */
  function finalGateOf(S) {
    var integ = integrityOf(S);
    var lost = lostCountOf(S);
    if (integ < CFG.BLANK_END || lost >= CFG.LOST_LIMIT) return 'blank';
    if (lost > 0) return 'half';
    return 'gate';
  }

  function pagesCountOf(S) {
    var n = 0;
    if (S && S.pages) {
      for (var k in S.pages) if (S.pages[k]) n++;
    }
    return n;
  }

  function relicCountOf(S) {
    var n = 0;
    if (S.relics) { n += S.relics.photo ? 1 : 0; n += S.relics.watch ? 1 : 0; n += S.relics.ribbon ? 1 : 0; }
    return n;
  }

  function hasRelics(S) { return relicCountOf(S) === 3; }

  function derived(S) {
    var d = {
      gold: (S && S.gold) || 0,
      integrity: integrityOf(S),
      lostCount: lostCountOf(S),
      pawned: pawnedOf(S),
      earliestRedeem: S ? earliestRedeemOf(S) : -1,
      relicCount: relicCountOf(S),
      allRelics: hasRelics(S)
    };
    if (S && S.phase === 'play' && S.t > 0 && (d.integrity < CFG.BLANK_END)) d.blankNow = true;
    else d.blankNow = false;
    return d;
  }

